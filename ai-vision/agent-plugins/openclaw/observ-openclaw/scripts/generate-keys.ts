#!/usr/bin/env tsx
/**
 * Build-time edition config embedding script.
 *
 * Reads EDITION and configs/*.config.json, then generates:
 *   - src/edition-config.generated.ts
 *
 * No keys are embedded. OpenClaw reports no longer require pk/sk.
 *
 * Usage:
 *   EDITION=aivision tsx scripts/generate-keys.ts
 *   EDITION=common tsx scripts/generate-keys.ts
 *   tsx scripts/generate-keys.ts              # common edition (default)
 */

import { writeFileSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import { loadEditionConfig } from './edition-config-source.mjs';

const __dirname = dirname(fileURLToPath(import.meta.url));
const ROOT = join(__dirname, '..');
const CONFIG_OUT = join(ROOT, 'src', 'edition-config.generated.ts');
const AIVISION_MIRROR = join(ROOT, 'configs', 'aivision.config.json');

const EDITIONS = ['common', 'aivision'] as const;
type Edition = typeof EDITIONS[number];

function generateEmbeddedConfig(edition: Edition, config: Record<string, unknown>): string {
  return `// AUTO-GENERATED by scripts/generate-keys.ts - do not edit.
// Edition: ${edition}

export const EMBEDDED_EDITION = ${JSON.stringify(edition)} as const;
export const EMBEDDED_CONFIG = ${JSON.stringify(config, null, 2)} as const;
`;
}

function resolveEdition(): Edition {
  const edition = process.env.EDITION?.trim() || 'common';
  if (!EDITIONS.includes(edition as Edition)) {
    throw new Error(`Unsupported EDITION "${edition}". Expected one of: ${EDITIONS.join(', ')}.`);
  }
  return edition as Edition;
}

const edition = resolveEdition();
const { config, sourcePath } = loadEditionConfig(edition);
if (edition === 'aivision') {
  // Checked-in mirror for reviewability; docs/config/openclaw.example.jsonc is the source of truth.
  writeFileSync(AIVISION_MIRROR, `${JSON.stringify(config, null, 2)}\n`, 'utf8');
}
writeFileSync(CONFIG_OUT, generateEmbeddedConfig(edition, config), 'utf-8');
console.log(`[generate] Edition: ${edition}`);
console.log(`[generate] Config source: ${sourcePath}`);

console.log(`[generate] Written -> ${CONFIG_OUT}`);
