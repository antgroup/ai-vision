// renderKubernetes emits a kustomize tree for every kind:container component:
// a Namespace, and per component a ConfigMap (non-sensitive env), a Secret with
// PLACEHOLDER values (credentials are never written into generated materials),
// a Deployment or StatefulSet, a Service and any PVC/volumeClaimTemplate.
// kind:process components are reported as skipped.
func renderKubernetes(app *runtime.App, comps []Resolved) ([]File, []string, error) {
	containers := containers(comps)
	if len(containers) == 0 {
		return nil, nil, fmt.Errorf("kubernetes target: blueprint has no kind:container components")
	}
	ns := k8sName(app.BP.Metadata.Namespace)
	if ns == "" {
		ns = "aivision"
	}

	warns := []string{"DEPRECATED generic Kubernetes materials are not a supported AI Vision installation: Operator, ingress and initialization lifecycle are omitted; use aiv cast --target kubernetes and the authoritative deploy/kubernetes resources"}
	if skipped := skippedProcesses(comps); len(skipped) > 0 {
		warns = append(warns, fmt.Sprintf(
			"kubernetes target skips host-process components (no image): %s — build them into images before deploying to a cluster",
			strings.Join(skipped, ", ")))
	}
	warns = append(warns, "kubernetes Secret values are PLACEHOLDERS (REPLACE_ME); the signoz org/API key are produced in-cluster by the backend bootstrap, never baked into manifests")

	files := []File{{Path: "README.md", Content: []byte("# Generic Kubernetes materials (deprecated)\n\nThese blueprint conversions are not a supported AI Vision installation. They omit the OB Operator, ingress and initialization/discovery lifecycle. Do not apply them as a replacement for the product deployment.\n\nUse `aiv cast --target kubernetes`. Reviewed product resources are maintained under the repository root `deploy/kubernetes/`; Kubernetes supports Operator-managed OceanBase CE only.\n")}}
	resources := []string{"namespace.yaml"}

	files = append(files, File{Path: "namespace.yaml", Content: []byte(fmt.Sprintf(
		"apiVersion: v1\nkind: Namespace\nmetadata:\n  name: %s\n  labels:\n    app.kubernetes.io/part-of: %s\n",
		ns, ns))})

	for _, c := range containers {
		name := k8sName(c.Name)
		if name == "" {
			name = c.Name
		}
		doc := renderK8sComponent(ns, name, c)
		path := name + ".yaml"
		files = append(files, File{Path: path, Content: []byte(doc)})
		resources = append(resources, path)
	}

	var kb strings.Builder
	kb.WriteString("# Generated by aiv generate --target kubernetes. DO NOT EDIT BY HAND.\n")
	kb.WriteString("apiVersion: kustomize.config.k8s.io/v1beta1\n")
	kb.WriteString("kind: Kustomization\n")
	kb.WriteString(fmt.Sprintf("namespace: %s\n", ns))
	kb.WriteString("resources:\n")
	for _, r := range resources {
		kb.WriteString(fmt.Sprintf("  - %s\n", r))
	}
	files = append(files, File{Path: "kustomization.yaml", Content: []byte(kb.String())})

	return files, warns, nil
}

// renderK8sComponent builds the multi-document manifest for one container.
func renderK8sComponent(ns, name string, c Resolved) string {
	labels := fmt.Sprintf("app.kubernetes.io/name: %s\n    app.kubernetes.io/part-of: %s", name, ns)

	// Split env into plain (ConfigMap) and sensitive (Secret placeholder) sets.
	var plainKeys, secretKeys []string
	for _, k := range sortedEnvKeys(c.Env) {
		if isSensitiveKey(k) {
			secretKeys = append(secretKeys, k)
		} else {
			plainKeys = append(plainKeys, k)
		}
	}

	namedVols, bindVols := k8sVolumes(c)
	// StatefulSet when the component owns persistent named volumes.
	kind := "Deployment"
	if len(namedVols) > 0 {
		kind = "StatefulSet"
	}

	var b strings.Builder
	b.WriteString(fmt.Sprintf("# Generated by aiv generate --target kubernetes: component %q.\n", c.Name))
	if c.Title != "" {
		b.WriteString(fmt.Sprintf("# %s\n", c.Title))
	}

	// ConfigMap
	if len(plainKeys) > 0 {
		b.WriteString("---\napiVersion: v1\nkind: ConfigMap\nmetadata:\n")
		b.WriteString(fmt.Sprintf("  name: %s-env\n  labels:\n    %s\n", name, labels))
		b.WriteString("data:\n")
		for _, k := range plainKeys {
			b.WriteString(fmt.Sprintf("  %s: %s\n", k, yamlQuote(c.Env[k])))
		}
	}

	// Secret (placeholders only)
	if len(secretKeys) > 0 {
		b.WriteString("---\napiVersion: v1\nkind: Secret\nmetadata:\n")
		b.WriteString(fmt.Sprintf("  name: %s-secret\n  labels:\n    %s\n", name, labels))
		b.WriteString("type: Opaque\nstringData:\n")
		for _, k := range secretKeys {
			b.WriteString(fmt.Sprintf("  %s: %s\n", k, yamlQuote("REPLACE_ME")))
		}
	}

	// Workload
	b.WriteString(fmt.Sprintf("---\napiVersion: apps/v1\nkind: %s\nmetadata:\n", kind))
	b.WriteString(fmt.Sprintf("  name: %s\n  labels:\n    %s\n", name, labels))
	b.WriteString("spec:\n")
	if kind == "Deployment" {
		b.WriteString("  replicas: 1\n")
	} else {
		b.WriteString("  serviceName: " + name + "\n")
	}
	b.WriteString("  selector:\n    matchLabels:\n")
	b.WriteString(fmt.Sprintf("      app.kubernetes.io/name: %s\n", name))
	b.WriteString("  template:\n    metadata:\n      labels:\n")
	b.WriteString(fmt.Sprintf("        %s\n", labels))
	b.WriteString("    spec:\n")
	if c.Network != "" {
		b.WriteString(fmt.Sprintf("      # blueprint docker network %q is implicit (cluster DNS) in k8s\n", c.Network))
	}
	b.WriteString("      containers:\n")
	b.WriteString(fmt.Sprintf("        - name: %s\n", name))
	b.WriteString(fmt.Sprintf("          image: %s\n", yamlQuote(c.Image)))
	if c.MemoryLimit != "" {
		limit := strings.ToUpper(c.MemoryLimit)
		for _, unit := range []string{"K", "M", "G", "T"} {
			if strings.HasSuffix(limit, unit) {
				limit += "i"
				break
			}
		}
		b.WriteString(fmt.Sprintf("          resources:\n            limits:\n              memory: %s\n", yamlQuote(limit)))
	}
	if len(c.Entrypoint) > 0 {
		b.WriteString("          command: " + yamlFlowSeq(c.Entrypoint) + "\n")
	}
	if len(c.Command) > 0 {
		b.WriteString("          args: " + yamlFlowSeq(c.Command) + "\n")
	}
	// ports
	cports := containerPorts(c)
	if len(cports) > 0 {
		b.WriteString("          ports:\n")
		for _, p := range cports {
			b.WriteString(fmt.Sprintf("            - name: %s\n              containerPort: %d\n              protocol: %s\n",
				p.name, p.port, strings.ToUpper(p.proto)))
		}
	}
	// envFrom
	if len(plainKeys) > 0 || len(secretKeys) > 0 {
		b.WriteString("          envFrom:\n")
		if len(plainKeys) > 0 {
			b.WriteString(fmt.Sprintf("            - configMapRef:\n                name: %s-env\n", name))
		}
		if len(secretKeys) > 0 {
			b.WriteString(fmt.Sprintf("            - secretRef:\n                name: %s-secret\n", name))
		}
	}
	// volumeMounts
	mounts := append(append([]k8sVol{}, namedVols...), bindVols...)
	if len(mounts) > 0 {
		b.WriteString("          volumeMounts:\n")
		for _, v := range mounts {
			b.WriteString(fmt.Sprintf("            - name: %s\n              mountPath: %s\n", v.name, yamlQuote(v.mountPath)))
			if v.readOnly {
				b.WriteString("              readOnly: true\n")
			}
		}
	}
	// probe (best-effort from Health)
	if pr := k8sProbe(c, cports); pr != "" {
		b.WriteString(pr)
	}
	// volumes (bind -> hostPath; named -> PVC for Deployment)
	if len(bindVols) > 0 || (len(namedVols) > 0 && kind == "Deployment") {
		b.WriteString("      volumes:\n")
		for _, v := range bindVols {
			b.WriteString(fmt.Sprintf("        - name: %s\n          hostPath:\n            path: %s\n", v.name, yamlQuote(v.hostPath)))
		}
		for _, v := range namedVols {
			b.WriteString(fmt.Sprintf("        - name: %s\n          persistentVolumeClaim:\n            claimName: %s\n", v.name, v.claimName))
		}
	}
	// volumeClaimTemplates (StatefulSet)
	if kind == "StatefulSet" && len(namedVols) > 0 {
		b.WriteString("  volumeClaimTemplates:\n")
		for _, v := range namedVols {
			b.WriteString(fmt.Sprintf("    - metadata:\n        name: %s\n      spec:\n", v.name))
			b.WriteString("        accessModes: [\"ReadWriteOnce\"]\n")
			b.WriteString("        resources:\n          requests:\n            storage: 1Gi\n")
		}
	}

	// Service
	if len(cports) > 0 {
		b.WriteString(fmt.Sprintf("---\napiVersion: v1\nkind: Service\nmetadata:\n  name: %s\n  labels:\n    %s\n", name, labels))
		b.WriteString("spec:\n  type: ClusterIP\n  selector:\n")
		b.WriteString(fmt.Sprintf("    app.kubernetes.io/name: %s\n", name))
		b.WriteString("  ports:\n")
		for _, p := range cports {
			b.WriteString(fmt.Sprintf("    - name: %s\n      port: %d\n      targetPort: %d\n      protocol: %s\n",
				p.name, p.port, p.port, strings.ToUpper(p.proto)))
		}
	}

	// PVCs for named volumes under a Deployment (StatefulSet uses claim templates)
	if kind == "Deployment" {
		for _, v := range namedVols {
			b.WriteString(fmt.Sprintf("---\napiVersion: v1\nkind: PersistentVolumeClaim\nmetadata:\n  name: %s\n  labels:\n    %s\n",
				v.claimName, labels))
			b.WriteString("spec:\n  accessModes: [\"ReadWriteOnce\"]\n  resources:\n    requests:\n      storage: 1Gi\n")
		}
	}

	return b.String()
}

// k8sVol is a resolved volume for a Kubernetes workload.
type k8sVol struct {
	name      string // volume/mount name (DNS-1123)
	mountPath string
	hostPath  string // bind mounts only
	claimName string // named volumes only
	readOnly  bool
}

// k8sVolumes splits -v/--mount specs into named (persistent) and bind (hostPath).
func k8sVolumes(c Resolved) (named, bind []k8sVol) {
	addNamed := func(source, target string, ro bool) {
		named = append(named, k8sVol{
			name:      volMountName(source, target),
			mountPath: target,
			claimName: k8sName(source) + "-data",
			readOnly:  ro,
		})
	}
	addBind := func(source, target string, ro bool) {
		bind = append(bind, k8sVol{
			name:      volMountName(source, target),
			mountPath: target,
			hostPath:  source,
			readOnly:  ro,
		})
	}
	for _, v := range c.Volumes {
		// docker -v spec: source:target[:mode]
		parts := strings.Split(v, ":")
		if len(parts) < 2 {
			continue
		}
		source, target := parts[0], parts[1]
		ro := len(parts) > 2 && strings.Contains(parts[2], "ro")
		if n := volumeName(v); n != "" {
			addNamed(source, target, ro)
		} else {
			addBind(source, target, ro)
		}
	}
	for _, m := range c.Mounts {
		ms := parseMount(m)
		if ms.Source == "" || ms.Target == "" {
			continue
		}
		if ms.Type == "volume" {
			addNamed(ms.Source, ms.Target, ms.ReadOnly)
		} else {
			addBind(ms.Source, ms.Target, ms.ReadOnly)
		}
	}
	return named, bind
}

// volMountName derives a stable DNS-1123 volume name, preferring the container
// mount path so it is unique per component.
func volMountName(source, target string) string {
	base := target
	if base == "" {
		base = source
	}
	n := k8sName(strings.TrimPrefix(base, "/"))
	if n == "" {
		n = k8sName(source)
	}
	if n == "" {
		n = "vol"
	}
	if len(n) > 63 {
		n = n[:63]
	}
	return n
}

// k8sPort is a resolved container port.
type k8sPort struct {
	name  string
	port  int
	proto string
}

// containerPorts extracts the container-side ports (deduped, named).
func containerPorts(c Resolved) []k8sPort {
	seen := map[string]bool{}
	var out []k8sPort
	for _, p := range c.Ports {
		ps := parsePort(p)
		if ps.ContainerPort == "" {
			continue
		}
		proto := ps.Proto
		if proto == "" {
			proto = "tcp"
		}
		name := proto + "-" + ps.ContainerPort
		if seen[name] {
			continue
		}
		seen[name] = true
		if len(name) > 15 {
			name = name[:15]
		}
		out = append(out, k8sPort{name: name, port: atoi(ps.ContainerPort), proto: proto})
	}
	return out
}

// k8sProbe renders a readinessProbe from component-local argv, TCP or HTTP
// health, indented for a container field, or "" when not derivable.
func k8sProbe(c Resolved, cports []k8sPort) string {
	if c.Health == nil || (len(cports) == 0 && len(c.Health.ExecArgv) == 0) {
		return ""
	}
	h := c.Health
	port := 0
	if len(cports) > 0 {
		port = cports[0].port
	}
	// Prefer a probe port matching the health TCP host port when mapped.
	if h.TCP != "" {
		if p := tcpContainerPort(c, h.TCP); p != "" {
			if n := atoi(p); n > 0 {
				port = n
			}
		}
	}
	var b strings.Builder
	b.WriteString("          readinessProbe:\n")
	if len(h.ExecArgv) > 0 {
		b.WriteString("            exec:\n")
		b.WriteString("              command: " + yamlFlowSeq(h.ExecArgv) + "\n")
		timeout, err := time.ParseDuration(h.Timeout)
		if err != nil {
			timeout = 3 * time.Second
		}
		timeoutSeconds := max(1, int(math.Ceil(timeout.Seconds())))
		b.WriteString(fmt.Sprintf("            timeoutSeconds: %d\n", timeoutSeconds))
	} else if h.HTTP != "" {
		path := "/"
		if i := strings.Index(h.HTTP, "://"); i >= 0 {
			if j := strings.IndexByte(h.HTTP[i+3:], '/'); j >= 0 {
				path = h.HTTP[i+3+j:]
			}
		}
		b.WriteString("            httpGet:\n")
		b.WriteString(fmt.Sprintf("              path: %s\n              port: %d\n", yamlQuote(path), port))
	} else {
		b.WriteString("            tcpSocket:\n")
		b.WriteString(fmt.Sprintf("              port: %d\n", port))
	}
	b.WriteString("            initialDelaySeconds: 5\n")
	b.WriteString("            periodSeconds: 10\n")
	return b.String()
}
