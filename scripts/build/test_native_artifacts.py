    def test_rejects_zip_member_limit_before_constructing_decoded_inventory(self):
        from unittest.mock import patch
        data = bytearray(self.zip())
        end = data.rfind(b"PK\x05\x06")
        data[end + 8:end + 12] = struct.pack("<HH", 20001, 20001)
        with patch.object(native_artifacts.zipfile, "ZipFile", side_effect=AssertionError("decoded too soon")):
            self.assertTrue(native_artifacts._source_issues("many.zip", bytes(data)))

    def test_streaming_tar_checks_metadata_without_classifying_upstream_payloads(self):
        class BoundedReads(io.BytesIO):
            def read(self, size=-1):
                if size < 0 or size > 65536:
                    raise AssertionError("unbounded stream read")
                return super().read(size)
        tar = self.tar(name="upstream/library.py")
        self.assertEqual(native_artifacts.tar_stream_issues("layer.tar", BoundedReads(tar)), [])
        self.assertTrue(native_artifacts.tar_stream_issues(
            "layer.tar", BoundedReads(tar + self.source)))

    def test_streaming_tar_skips_large_upstream_bodies_and_enforces_metadata_bounds(self):
        output = io.BytesIO()
        with tarfile.open(fileobj=output, mode="w") as archive:
            member = tarfile.TarInfo("upstream/library.py")
            payload = self.source * 5000
            member.size = len(payload)
            archive.addfile(member, io.BytesIO(payload))
        class BoundedReads(io.BytesIO):
            def read(self, size=-1):
                if not 0 <= size <= 65536:
                    raise AssertionError("unbounded stream read")
                return super().read(size)
        self.assertEqual(native_artifacts.tar_stream_issues(
            "layer.tar", BoundedReads(output.getvalue())), [])
        self.assertTrue(native_artifacts.tar_stream_issues(
            "layer.tar", io.BytesIO(self.tar()), max_members=0))
        self.assertTrue(native_artifacts.tar_stream_issues(
            "layer.tar", io.BytesIO(self.tar(name="a" * 150)), max_metadata_bytes=10))


