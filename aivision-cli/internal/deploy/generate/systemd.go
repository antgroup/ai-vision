package generate

import (
	"fmt"
	"path/filepath"
	"strings"

	"github.com/antgroup/ai-vision/aivision-cli/internal/deploy/runtime"
)

// renderSystemd emits one .service per component plus a grouping .target.
// kind:container components become `docker run` units (env passed via a
// docker --env-file so credentials stay out of the unit); kind:process
// components become native units that exec a generated run script (env exported
// inside the script). Env files and run scripts are emitted alongside the units
// and must be installed under opts.Prefix (referenced by the units).
func renderSystemd(app *runtime.App, comps []Resolved, opts Options) ([]File, []string, error) {
	if len(comps) == 0 {
		return nil, nil, fmt.Errorf("systemd target: blueprint has no components")
	}
	ns := k8sName(app.BP.Metadata.Namespace)
	if ns == "" {
		ns = "aivision"
	}
	targetUnit := "aivision-" + ns + ".target"

	// Map component name -> unit base so dependsOn can be wired.
	unitOf := map[string]string{}
	for _, c := range comps {
		unitOf[c.Name] = "aivision-" + ns + "-" + k8sName(c.Name)
	}

	files := []File{}
	var warns []string
	var serviceUnits []string

	for _, c := range comps {
		unit := unitOf[c.Name]
		serviceUnits = append(serviceUnits, unit+".service")

		depUnits := depUnitList(c, unitOf)
		envFileName := c.Name + ".env"
		envFilePath := opts.Prefix + "/" + envFileName

		var svc string
		if c.Kind == "container" {
			if len(c.Env) > 0 {
				files = append(files, File{Path: envFileName, Content: []byte(dockerEnvFile(c.Env))})
			}
			svc = renderContainerUnit(c, unit, targetUnit, depUnits, envFilePath, opts)
		} else {
			scriptName := c.Name + ".run.sh"
			scriptPath := opts.Prefix + "/" + scriptName
			files = append(files, File{Path: scriptName, Content: []byte(renderRunScript(app, c))})
			svc = renderProcessUnit(c, unit, targetUnit, depUnits, scriptPath, opts)
		}
		files = append(files, File{Path: unit + ".service", Content: []byte(svc)})
	}

	// grouping target
	var tb strings.Builder
	tb.WriteString("# Generated by aiv generate --target systemd. DO NOT EDIT BY HAND.\n")
	tb.WriteString(fmt.Sprintf("# Install: copy *.service to /etc/systemd/system (or `systemctl --user`), and\n"))
	tb.WriteString(fmt.Sprintf("# copy the *.env / *.run.sh files to %s, then `systemctl daemon-reload`.\n", opts.Prefix))
	tb.WriteString("[Unit]\n")
	tb.WriteString(fmt.Sprintf("Description=AI Vision stack (%s)\n", ns))
	tb.WriteString("Wants=" + strings.Join(serviceUnits, " ") + "\n")
	tb.WriteString("After=" + strings.Join(serviceUnits, " ") + "\n")
	tb.WriteString("\n[Install]\nWantedBy=multi-user.target\n")
	files = append(files, File{Path: targetUnit, Content: []byte(tb.String())})

	warns = append(warns, fmt.Sprintf(
		"systemd units reference env/script files under %s — install the generated *.env and *.run.sh there before enabling the units",
		opts.Prefix))

	return files, warns, nil
}

// depUnitList maps a component's dependsOn to sibling unit names (only deps that
// are themselves components in this blueprint).
func depUnitList(c Resolved, unitOf map[string]string) []string {
	var out []string
	for _, d := range c.DependsOn {
		if u, ok := unitOf[d]; ok {
			out = append(out, u+".service")
		}
	}
	return out
}

// renderContainerUnit builds a `docker run` based .service for a container.
func renderContainerUnit(c Resolved, unit, targetUnit string, depUnits []string, envFilePath string, opts Options) string {
	cn := c.ContainerName
	if cn == "" {
		cn = unit
	}
	var b strings.Builder
	b.WriteString("# Generated by aiv generate --target systemd. DO NOT EDIT BY HAND.\n")
	b.WriteString("[Unit]\n")
	b.WriteString(fmt.Sprintf("Description=%s (container)\n", oneLine(c.Title, c.Name)))
	b.WriteString("Wants=network-online.target docker.service\n")
	b.WriteString("Requires=docker.service\n")
	b.WriteString("After=network-online.target docker.service")
	appendUnits(&b, depUnits)
	for _, d := range depUnits {
		b.WriteString("Wants=" + d + "\n")
	}
	b.WriteString(fmt.Sprintf("PartOf=%s\n", targetUnit))
	b.WriteString("\n[Service]\n")
	b.WriteString("Restart=on-failure\n")
	b.WriteString("RestartSec=5s\n")
	b.WriteString("TimeoutStartSec=0\n")
	b.WriteString(fmt.Sprintf("ExecStartPre=-/usr/bin/docker rm -f %s\n", shq(cn)))
	if c.Network != "" {
		b.WriteString(fmt.Sprintf("ExecStartPre=-/usr/bin/docker network create %s\n", shq(c.Network)))
	}
	b.WriteString(renderDockerRun(c, cn, envFilePath))
	b.WriteString(fmt.Sprintf("ExecStop=/usr/bin/docker stop -t 10 %s\n", shq(cn)))
	b.WriteString("\n[Install]\n")
	b.WriteString(fmt.Sprintf("WantedBy=%s\n", targetUnit))
	return b.String()
}

// renderDockerRun assembles the ExecStart docker-run invocation with `\`
// continuations. Env is passed via --env-file; ports/volumes/mounts pass through
// their docker specs; Command becomes trailing args.
func renderDockerRun(c Resolved, cn, envFilePath string) string {
	var args []string
	args = append(args, "--rm", "--name", shq(cn))
	if c.Network != "" {
		args = append(args, "--network", shq(c.Network))
	}
	if len(c.Env) > 0 {
		args = append(args, "--env-file", shq(envFilePath))
	}
	for _, p := range c.Ports {
		args = append(args, "-p", shq(p))
	}
	for _, v := range c.Volumes {
		args = append(args, "-v", shq(v))
	}
	for _, m := range c.Mounts {
		args = append(args, "--mount", shq(m))
	}
	if c.MemoryLimit != "" {
		args = append(args, "--memory", shq(c.MemoryLimit))
	}
	image := c.Image
	var tail []string
	if len(c.Entrypoint) > 0 {
		args = append(args, "--entrypoint", shq(c.Entrypoint[0]))
		tail = append(tail, c.Entrypoint[1:]...)
	}
	tail = append(tail, c.Command...)

	var b strings.Builder
	b.WriteString("ExecStart=/usr/bin/docker run \\\n")
	for _, a := range args {
		b.WriteString("  " + a + " \\\n")
	}
	b.WriteString("  " + shq(image))
	for _, t := range tail {
		b.WriteString(" " + shq(t))
	}
	b.WriteString("\n")
	return b.String()
}

// renderProcessUnit builds a native .service that execs a generated run script.
func renderProcessUnit(c Resolved, unit, targetUnit string, depUnits []string, scriptPath string, opts Options) string {
	wd := c.Workdir
	if wd == "" {
		wd = c.Dir
	}
	var b strings.Builder
	b.WriteString("# Generated by aiv generate --target systemd. DO NOT EDIT BY HAND.\n")
	b.WriteString("[Unit]\n")
	b.WriteString(fmt.Sprintf("Description=%s (process)\n", oneLine(c.Title, c.Name)))
	b.WriteString("Wants=network-online.target\n")
	b.WriteString("After=network-online.target")
	appendUnits(&b, depUnits)
	for _, d := range depUnits {
		b.WriteString("Wants=" + d + "\n")
	}
	b.WriteString(fmt.Sprintf("PartOf=%s\n", targetUnit))
	b.WriteString("\n[Service]\n")
	b.WriteString("Type=simple\n")
	b.WriteString("Restart=on-failure\n")
	b.WriteString("RestartSec=5s\n")
	b.WriteString("TimeoutStartSec=0\n")
	if wd != "" {
		b.WriteString(fmt.Sprintf("WorkingDirectory=%s\n", shq(wd)))
	}
	b.WriteString(fmt.Sprintf("ExecStart=/bin/bash %s\n", shq(scriptPath)))
	b.WriteString("\n[Install]\n")
	b.WriteString(fmt.Sprintf("WantedBy=%s\n", targetUnit))
	return b.String()
}

// renderRunScript writes the process run script: exported env then the run body.
func renderRunScript(app *runtime.App, c Resolved) string {
	wd := c.Workdir
	if wd == "" {
		wd = c.Dir
	}
	if wd != "" && !filepath.IsAbs(wd) {
		wd = filepath.Join(app.SourceRoot(), wd)
	}
	var b strings.Builder
	b.WriteString("#!/usr/bin/env bash\n")
	b.WriteString("# Generated by aiv generate --target systemd. DO NOT EDIT BY HAND.\n")
	b.WriteString("set -euo pipefail\n")
	for _, k := range sortedEnvKeys(c.Env) {
		b.WriteString(fmt.Sprintf("export %s=%s\n", k, shSingleQuote(c.Env[k])))
	}
	if wd != "" {
		b.WriteString("cd " + shSingleQuote(wd) + "\n")
	}
	b.WriteString(c.Run)
	if !strings.HasSuffix(c.Run, "\n") {
		b.WriteString("\n")
	}
	return b.String()
}

// dockerEnvFile renders KEY=VALUE lines for `docker run --env-file` (literal
// values, no quoting) in deterministic order.
func dockerEnvFile(env map[string]string) string {
	var b strings.Builder
	b.WriteString("# Generated by aiv generate --target systemd. DO NOT EDIT BY HAND.\n")
	for _, k := range sortedEnvKeys(env) {
		v := strings.ReplaceAll(env[k], "\n", " ")
		b.WriteString(fmt.Sprintf("%s=%s\n", k, v))
	}
	return b.String()
}

// appendUnits writes trailing " <unit>" tokens to an After=/Wants= line and
// terminates it with a newline.
func appendUnits(b *strings.Builder, units []string) {
	for _, u := range units {
		b.WriteString(" " + u)
	}
	b.WriteString("\n")
}

// oneLine returns title (single line) or fallback.
func oneLine(title, fallback string) string {
	t := strings.TrimSpace(strings.SplitN(title, "\n", 2)[0])
	if t == "" {
		return fallback
	}
	return t
}

// shq double-quotes a token for systemd ExecStart argument splitting.
func shq(s string) string {
	if s == "" {
		return `""`
	}
	if strings.ContainsAny(s, " \t\"'\\$`") {
		return `"` + strings.NewReplacer(`\`, `\\`, `"`, `\"`, `$`, `\$`, "`", "\\`").Replace(s) + `"`
	}
	return s
}

// shSingleQuote single-quotes a shell argument, escaping embedded single quotes.
func shSingleQuote(s string) string {
	return "'" + strings.ReplaceAll(s, "'", `'\''`) + "'"
}
