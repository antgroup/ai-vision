def rel(path: Path) -> str:
    return path.relative_to(REPO_ROOT).as_posix()


def md_escape(value: Any) -> str:
    text = str(value if value is not None else "")
    return text.replace("|", "\\|").replace("\n", "<br>")


def code(value: Any) -> str:
    if value is None or value == "":
        return "—"
    return f"`{md_escape(value)}`"


def list_code(values: Iterable[Any]) -> str:
    items = list(values or [])
    return ", ".join(code(item) for item in items) if items else "—"


def display_field_token(value: Any) -> str:
    text = str(value if value is not None else "").strip()
    return f"{text}*" if text.endswith(".") else text


def subject_token(subject: Any) -> str:
    if not isinstance(subject, Mapping):
        return display_field_token(subject)
    kind = str(subject.get("kind", "")).strip()
    value = display_field_token(subject.get("value", ""))
    if not kind:
        return value
    if kind == "field":
        return value
    if kind == "prefix":
        return f"prefix: {value}"
    return f"{kind}: {value}"


def rule_subject_field_code(rule: Mapping[str, Any]) -> str:
    subjects = rule.get("subjects") or []
    if subjects:
        return list_code(subject_token(subject) for subject in subjects)
    return list_code(display_field_token(item) for item in rule.get("fields", []))


def replacement_token(value: Any) -> str:
    subject = parse_rule_subject(str(value or ""))
    return subject_token(subject) if subject else display_field_token(value)


def rule_purpose_with_replacement(rule: Mapping[str, Any]) -> str:
    purpose = str(rule.get("purpose_zh") or rule.get("title_zh") or "—")
    replacement = rule.get("replacement")
    if rule.get("constraint_type") != "forbidden_presence" or not replacement:
        return purpose
    replacement_label = replacement_token(replacement)
    if replacement_label and replacement_label not in purpose:
        return f"{purpose} 替代字段：`{replacement_label}`。"
    return purpose


def render_table(headers: List[str], rows: List[List[Any]]) -> str:
    out = ["| " + " | ".join(headers) + " |", "| " + " | ".join(["---"] * len(headers)) + " |"]
    if not rows:
        out.append("| " + " | ".join(["—"] * len(headers)) + " |")
    else:
        for row in rows:
            out.append("| " + " | ".join(md_escape(cell) for cell in row) + " |")
    return "\n".join(out)


def iter_policy_rego_files(include_generated: bool = False) -> List[Path]:
    if not POLICY_ROOT.exists():
        return []
    files = []
    for path in sorted(POLICY_ROOT.rglob("*.rego")):
        if not include_generated and "generated" in path.relative_to(POLICY_ROOT).parts:
            continue
        files.append(path)
    return files


def policy_dirs() -> List[Path]:
    if not POLICY_ROOT.exists():
        return []
    dirs = []
    for path in sorted(POLICY_ROOT.rglob("*")):
        if path.is_dir() and path != POLICY_ROOT and "generated" not in path.relative_to(POLICY_ROOT).parts:
            dirs.append(path)
    return dirs


def policy_signal_from_path(path: Path) -> str:
    try:
        first = path.relative_to(POLICY_ROOT).parts[0]
    except (ValueError, IndexError):
        return "unknown"
    return {"events": "events", "traces": "spans", "metrics": "metrics"}.get(first, first)


def policy_entity_from_path(path: Path) -> str:
    try:
        parts = path.relative_to(POLICY_ROOT).parts
    except ValueError:
        return "policy:unknown"
    if len(parts) < 2:
        return f"policy:{parts[0] if parts else 'unknown'}"
    root = parts[0]
    section = parts[1]
    if root == "events":
        if section == "resource_attributes":
            return "resource:events"
        if section == "common_attributes":
            return "event:common"
        return f"event:{section}"
    if root == "traces":
        if section == "resource_attributes":
            return "resource:traces"
        if section == "span_attributes":
            return "span:common"
        return f"span:{section}"
    if root == "metrics":
        return f"metric:{section}"
    return f"{root}:{section}"


def policy_category_from_path(path: Path) -> str:
    name = path.name
    if "violations_required" in name:
        return "必须属性"
    if "improvements_recommended" in name:
        return "推荐属性"
    if "violations_forbidden" in name:
        return "禁用字段"
    if "violations_format" in name:
        return "格式校验"
    if "violations_compatibility" in name or "improvements_compatibility" in name:
        return "兼容性迁移"
    if "information_optional" in name:
        return "可选信息"
    if "metric" in name:
        return "指标约束"
    return "语义规则"


def parse_rule_subject(value: str) -> Dict[str, str] | None:
    if ":" not in value:
        return None
    kind, subject_value = value.split(":", 1)
    kind = kind.strip()
    subject_value = subject_value.strip()
    if kind not in {"field", "prefix"} or not subject_value:
        return None
    return {"kind": kind, "value": subject_value}


def rule_comment_metadata(text: str, rule_start: int) -> Tuple[Dict[str, Any], int]:
    line_spans: List[Tuple[int, str]] = []
    offset = 0
    for line in text[:rule_start].splitlines(True):
        line_spans.append((offset, line.rstrip("\n\r")))
        offset += len(line)

    lines: List[str] = []
    source_start = rule_start
    saw_comment = False
    for line_start, line in reversed(line_spans):
        stripped = line.strip()
        if not stripped:
            if saw_comment:
                break
            source_start = line_start
            continue
        if stripped.startswith("#"):
            saw_comment = True
            source_start = line_start
            lines.append(stripped)
            continue
        break

    metadata: Dict[str, Any] = {"fields": [], "subjects": [], "allowed_values": []}
    for line in reversed(lines):
        content = line.lstrip("#").strip()
        if ":" not in content:
            continue
        key, value = content.split(":", 1)
        key = key.strip()
        value = value.strip()
        if not value:
            continue
        if key in {"@weaver.rule.title.zh", "@rule.title.zh", "weaver.rule.title.zh", "rule.title.zh"}:
            metadata["title_zh"] = value
        elif key in {"@weaver.rule.zh", "@rule.zh", "weaver.rule.zh", "rule.zh"}:
            metadata.setdefault("title_zh", value)
            metadata["purpose_zh"] = value
        elif key in {"@weaver.rule.check.zh", "@rule.check.zh", "weaver.rule.check.zh", "rule.check.zh"}:
            metadata["check_zh"] = value
        elif key in {"@weaver.rule.fix.zh", "@rule.fix.zh", "weaver.rule.fix.zh", "rule.fix.zh"}:
            metadata["fix_zh"] = value
        elif key in {"@weaver.rule.note.zh", "@rule.note.zh", "weaver.rule.note.zh", "rule.note.zh"}:
            metadata["note_zh"] = value
        elif key in {"@weaver.rule.entity", "@weaver.entity", "@rule.entity", "weaver.rule.entity"}:
            metadata["entity"] = value
        elif key in {"@weaver.rule.category.zh", "@weaver.category.zh", "@rule.category.zh", "weaver.rule.category.zh"}:
            metadata["category_zh"] = value
        elif key in {"@weaver.rule.fields", "@weaver.fields", "@rule.fields", "weaver.rule.fields"}:
            metadata["fields"].extend(field.strip() for field in value.split(",") if field.strip())
        elif key in {"@weaver.rule.subject", "@rule.subject", "weaver.rule.subject", "rule.subject"}:
            subject = parse_rule_subject(value)
            if subject:
                metadata["subjects"].append(subject)
        elif key in {"@weaver.rule.placement", "@rule.placement", "weaver.rule.placement"}:
            metadata["placement"] = value
        elif key in {"@weaver.rule.constraint.type", "@rule.constraint.type", "weaver.rule.constraint.type", "rule.constraint.type"}:
            metadata["constraint_type"] = value
        elif key in {"@weaver.rule.allowed_values", "@rule.allowed_values", "weaver.rule.allowed_values", "rule.allowed_values"}:
            metadata["allowed_values"].extend(item.strip() for item in value.split(",") if item.strip())
        elif key in {"@weaver.rule.expected_value", "@rule.expected_value", "weaver.rule.expected_value", "rule.expected_value"}:
            metadata["expected_value"] = value
        elif key in {"@weaver.rule.replacement", "@rule.replacement", "weaver.rule.replacement"}:
            metadata["replacement"] = value
        elif key in {"@weaver.rule.when.zh", "@rule.when.zh", "weaver.rule.when.zh"}:
            metadata["when_zh"] = value
        elif key in {"@weaver.rule.branch", "@rule.branch", "weaver.rule.branch"}:
            metadata["branch"] = value
    return metadata, source_start


def inferred_fields(block: str) -> List[str]:
    values = re.findall(r'"([A-Za-z0-9_.:-]+)"', block)
    return sorted({value for value in values if "." in value and not value.startswith("policy:")})


def current_rego_rule_clauses() -> List[Dict[str, Any]]:
    clauses: List[Dict[str, Any]] = []
    deny_re = re.compile(r"(?m)^\s*deny\s+contains\s+make_advice\s*\(")
    for path in iter_policy_rego_files():
        if path.name == "helpers.rego":
            continue
        text = path.read_text(encoding="utf-8")
        occurrences: Dict[str, int] = defaultdict(int)
        matches = list(deny_re.finditer(text))
        for index, match in enumerate(matches):
            start = match.start()
            next_start = matches[index + 1].start() if index + 1 < len(matches) else len(text)
            metadata, source_start = rule_comment_metadata(text, start)
            block = text[start:next_start]
            strings = re.findall(r'"((?:[^"\\]|\\.)*)"', block)
            rule_id = strings[0] if len(strings) >= 1 else "UNKNOWN_RULE_ID"
            level = strings[1] if len(strings) >= 2 else "unknown"
            occurrences[rule_id] += 1
            fields = metadata.get("fields") or inferred_fields(block)
            clauses.append({
                "key": (rel(path), rule_id, occurrences[rule_id]),
                "path": rel(path),
                "rule_id": rule_id,
                "level": level,
                "signal": policy_signal_from_path(path),
                "entity": metadata.get("entity") or policy_entity_from_path(path),
                "category_zh": metadata.get("category_zh") or policy_category_from_path(path),
                "title_zh": metadata.get("title_zh"),
                "purpose_zh": metadata.get("purpose_zh"),
                "check_zh": metadata.get("check_zh"),
                "fix_zh": metadata.get("fix_zh"),
                "note_zh": metadata.get("note_zh"),
                "fields": fields,
                "subjects": metadata.get("subjects") or [],
                "placement": metadata.get("placement"),
                "constraint_type": metadata.get("constraint_type"),
                "allowed_values": metadata.get("allowed_values") or [],
                "expected_value": metadata.get("expected_value"),
                "replacement": metadata.get("replacement"),
                "when_zh": metadata.get("when_zh"),
                "branch": metadata.get("branch"),
                "occurrence": occurrences[rule_id],
                "line": text[:start].count("\n") + 1,
                "source": text[source_start:next_start].strip(),
            })
    return clauses


def rule_variant(rule: Mapping[str, Any]) -> str:
    branch = rule.get("branch")
    if branch:
        return str(branch)
    occurrence = int(rule.get("occurrence") or 1)
    return f"occurrence-{occurrence}" if occurrence > 1 else "—"


def level_label(level: Any) -> str:
    value = str(level or "")
    return {
        "violation": "violation",
        "improvement": "improvement",
        "information": "information",
    }.get(value, value or "—")


def entity_title(entity: str) -> str:
    if entity in ENTITY_LABELS:
        return ENTITY_LABELS[entity]
    if ":" not in entity:
        return entity
    kind, name = entity.split(":", 1)
    if kind == "event":
        return f"event:{name} 事件约束"
    if kind == "span":
        return f"span:{name} 约束"
    if kind == "metric":
        return f"metric:{name} 约束"
    if kind == "resource":
        return f"{name} Resource 属性约束"
    return entity


def entity_sort_key(entity: str) -> Tuple[int, str]:
    order = {
        "resource:events": 0,
        "resource:traces": 0,
        "event:common": 1,
        "span:common": 1,
        "metric:common": 1,
        "event:base": 2,
        "span:base": 2,
        "metric:base": 2,
    }
    return (order.get(entity, 10), entity)


def rule_sort_key(rule: Mapping[str, Any]) -> Tuple[Any, ...]:
    return (
        entity_sort_key(str(rule.get("entity", ""))),
        str(rule.get("category_zh") or ""),
        str(rule.get("constraint_type") or ""),
        str(rule.get("rule_id") or ""),
        int(rule.get("occurrence") or 1),
    )


def grouped_by_entity(rules: Iterable[Mapping[str, Any]]) -> Dict[str, List[Mapping[str, Any]]]:
    grouped: Dict[str, List[Mapping[str, Any]]] = defaultdict(list)
    for rule in rules:
        grouped[str(rule.get("entity") or "unknown")].append(rule)
    for items in grouped.values():
        items.sort(key=rule_sort_key)
    return dict(sorted(grouped.items(), key=lambda item: entity_sort_key(item[0])))


def rule_rows(rules: Iterable[Mapping[str, Any]], include_source: bool = False) -> List[List[Any]]:
    rows: List[List[Any]] = []
    for rule in sorted(rules, key=rule_sort_key):
        row = [
            code(rule.get("rule_id")),
            rule_variant(rule),
            level_label(rule.get("level")),
            rule.get("category_zh") or "—",
            rule_subject_field_code(rule),
            rule.get("constraint_type") or "—",
            rule.get("placement") or "—",
            rule_purpose_with_replacement(rule),
            rule.get("check_zh") or "—",
            rule.get("fix_zh") or "—",
        ]
        if include_source:
            row.append(f"{rule.get('path')}:{rule.get('line')}")
        rows.append(row)
    return rows


def render_rule_matrix(rules: Iterable[Mapping[str, Any]], include_source: bool = False) -> str:
    headers = ["rule", "variant", "level", "分组", "字段/subject", "约束", "位置", "规则作用", "命中条件", "修复建议"]
    if include_source:
        headers.append("Rego")
    return render_table(headers, rule_rows(rules, include_source=include_source))


def render_entity_sections(rules: Iterable[Mapping[str, Any]]) -> List[str]:
    out: List[str] = []
    for entity, items in grouped_by_entity(rules).items():
        out.extend([
            f"## {entity_title(entity)}",
            "",
            f"- 语义对象：`{entity}`",
            f"- 规则数：`{len(items)}`",
            "",
            render_rule_matrix(items, include_source=True),
            "",
        ])
    return out


def render_signal_doc(signal: str, rules: List[Mapping[str, Any]]) -> str:
    title, purpose = SIGNAL_TITLES[signal]
    signal_rules = [rule for rule in rules if rule.get("signal") == signal]
    by_level: Dict[str, int] = defaultdict(int)
    by_category: Dict[str, int] = defaultdict(int)
    for rule in signal_rules:
        by_level[str(rule.get("level") or "unknown")] += 1
        by_category[str(rule.get("category_zh") or "未分类")] += 1
    summary_rows = (
        [["rules", len(signal_rules)]]
        + [[f"level:{key}", value] for key, value in sorted(by_level.items())]
        + [[f"category:{key}", value] for key, value in sorted(by_category.items())]
    )
    out = [
        GENERATED_MARKER,
        f"# {title}",
        "",
        purpose,
        "",
        "Rego 是本文件唯一输入源。修改规则说明、字段归类、命中条件或修复建议时，编辑对应 Rego 规则前的 `@weaver.rule.*` 注释，然后运行 `make -C weaver spec-generate`。",
        "",
        "## 汇总",
        "",
        render_table(["项目", "数量"], summary_rows),
        "",
    ]
    out.extend(render_entity_sections(signal_rules))
    return "\n".join(out).rstrip() + "\n"


def render_rules_doc(rules: List[Mapping[str, Any]]) -> str:
    by_signal: Dict[str, int] = defaultdict(int)
    by_level: Dict[str, int] = defaultdict(int)
    by_category: Dict[str, int] = defaultdict(int)
    for rule in rules:
        by_signal[str(rule.get("signal") or "unknown")] += 1
        by_level[str(rule.get("level") or "unknown")] += 1
        by_category[str(rule.get("category_zh") or "未分类")] += 1
    rows = []
    for rule in sorted(rules, key=rule_sort_key):
        rows.append([
            code(rule.get("rule_id")),
            rule_variant(rule),
            level_label(rule.get("level")),
            rule.get("signal") or "—",
            rule.get("entity") or "—",
            rule.get("category_zh") or "—",
            rule_subject_field_code(rule),
            f"{rule.get('path')}:{rule.get('line')}",
            rule_purpose_with_replacement(rule),
        ])
    return "\n".join([
        GENERATED_MARKER,
        "# AiVision Rego 规则目录",
        "",
        "本文件从 `weaver/policies/aivision/**/*.rego` 的 `@weaver.rule.*` 注释生成。Rego 是唯一规则、字段矩阵和人类语义输入源。",
        "",
        "## 汇总",
        "",
        render_table(["项目", "数量"],
                     [["rules", len(rules)]]
                     + [[f"signal:{key}", value] for key, value in sorted(by_signal.items())]
                     + [[f"level:{key}", value] for key, value in sorted(by_level.items())]
                     + [[f"category:{key}", value] for key, value in sorted(by_category.items())]),
        "",
        "## 规则清单",
        "",
        render_table(["rule", "variant", "level", "signal", "entity", "分组", "字段/subject", "Rego", "规则作用"], rows),
    ]).rstrip() + "\n"


def directory_entity(path: Path) -> str:
    parts = path.relative_to(POLICY_ROOT).parts
    if len(parts) == 1:
        return f"signal:{parts[0]}"
    root, section = parts[0], parts[1]
    if root == "events":
        if section == "resource_attributes":
            return "resource:events"
        if section == "common_attributes":
            return "event:common"
        return f"event:{section}"
    if root == "traces":
        if section == "resource_attributes":
            return "resource:traces"
        if section == "span_attributes":
            return "span:common"
        return f"span:{section}"
    if root == "metrics":
        return f"metric:{section}"
    return ":".join(parts)


def rules_under_dir(path: Path, rules: Iterable[Mapping[str, Any]]) -> List[Mapping[str, Any]]:
    prefix = rel(path) + "/"
    return [rule for rule in rules if str(rule.get("path") or "").startswith(prefix)]


def render_policy_dir_readme(path: Path, rules: List[Mapping[str, Any]]) -> str:
    entity = directory_entity(path)
    dir_rules = rules_under_dir(path, rules)
    parts = path.relative_to(POLICY_ROOT).parts
    if len(parts) == 1:
        title, purpose = SIGNAL_TITLES.get(
            {"traces": "spans"}.get(parts[0], parts[0]),
            (f"AiVision {parts[0]} Rego 规则", "AiVision Rego 规则集合。"),
        )
    else:
        title = entity_title(entity)
        purpose = f"`{rel(path)}` 下的 Rego 规则集合。"
    helper_rows = []
    for helper in sorted(path.glob("helpers.rego")):
        helper_rows.append([code(helper.name), "提供当前目录/信号的 Rego helper；不包含 make_advice 规则。"])
    out = [
        GENERATED_MARKER,
        f"# {title}",
        "",
        purpose,
        "",
        "Rego 是本 README 的唯一输入源。修改字段含义、等级、命中条件或修复建议时，编辑同目录 Rego 中紧邻 `deny contains make_advice(...)` 的 `@weaver.rule.*` 注释。",
        "",
        "## 规则汇总",
        "",
        render_table(["项目", "数量"], [["rules", len(dir_rules)], ["entity", entity]]),
        "",
    ]
    if helper_rows:
        out.extend(["## Helper", "", render_table(["文件", "职责"], helper_rows), ""])
    out.extend(["## 规则矩阵", "", render_rule_matrix(dir_rules, include_source=True)])
    return "\n".join(out).rstrip() + "\n"


def outputs() -> Dict[Path, str]:
    rules = current_rego_rule_clauses()
    out: Dict[Path, str] = {
        REPO_ROOT / "docs/aivision-events.md": render_signal_doc("events", rules),
        REPO_ROOT / "docs/aivision-traces.md": render_signal_doc("spans", rules),
        REPO_ROOT / "docs/aivision-rules.md": render_rules_doc(rules),
    }
    for directory in policy_dirs():
        out[directory / "README.md"] = render_policy_dir_readme(directory, rules)
    return out


def retired_spec_errors() -> List[str]:
    errors: List[str] = []
    for pattern in RETIRED_SPEC_GLOBS:
        for path in sorted(REPO_ROOT.glob(pattern)):
            errors.append(f"{rel(path)} is retired; Rego comments are the only AiVision spec_sync input source")
    return errors


def generated_rego_errors() -> List[str]:
    if not POLICY_ROOT.exists():
        return []
    return [
        f"{rel(path)} is forbidden; generated Rego must not be part of the policy tree"
        for path in sorted(POLICY_ROOT.glob("**/generated/*.rego"))
    ]


def policy_annotation_errors() -> List[str]:
    errors: List[str] = []
    clauses = current_rego_rule_clauses()
    seen: Dict[Tuple[str, str], int] = defaultdict(int)
    presence_bucket_by_subject: Dict[Tuple[str, str, str], Dict[str, List[str]]] = defaultdict(lambda: defaultdict(list))
    positive_area_by_subject: Dict[Tuple[str, str, str], Dict[str, List[str]]] = defaultdict(lambda: defaultdict(list))
    event_required_subject_locations: Dict[str, Dict[str, List[str]]] = defaultdict(lambda: defaultdict(list))
    trace_required_subject_locations: Dict[str, Dict[str, List[str]]] = defaultdict(lambda: defaultdict(list))
    field_like_categories = {"必须属性", "推荐属性", "禁用字段", "固定值", "枚举值", "格式校验"}
    known_constraint_types = {
        "required_presence",
        "recommended_presence",
        "forbidden_presence",
        "enum",
        "fixed_value",
        "format",
        "placement",
        "namespace",
        "compatibility",
        "optional_info",
        "invariant",
    }
    subject_required_constraint_types = {
        "required_presence",
        "recommended_presence",
        "forbidden_presence",
        "enum",
        "fixed_value",
        "format",
        "placement",
        "compatibility",
        "optional_info",
        "invariant",
    }
    for clause in clauses:
        location = f"{clause['path']}:{clause['line']} {clause['rule_id']}"
        for field in ("entity", "category_zh", "title_zh", "purpose_zh", "check_zh", "fix_zh"):
            if not clause.get(field):
                errors.append(f"{location}: missing @weaver.rule metadata {field}")
        seen[(clause["path"], clause["rule_id"])] += 1
        if seen[(clause["path"], clause["rule_id"])] > 1 and not clause.get("branch"):
            errors.append(f"{location}: repeated rule_id requires @weaver.rule.branch")
        if clause.get("category_zh") in field_like_categories and not clause.get("fields") and not clause.get("subjects"):
            errors.append(f"{location}: {clause.get('category_zh')} rule requires @weaver.rule.fields or inferable field strings")
        constraint_type = clause.get("constraint_type")
        subjects = clause.get("subjects") or []
        if not constraint_type:
            errors.append(f"{location}: missing @weaver.rule.constraint.type")
        elif constraint_type not in known_constraint_types:
            errors.append(f"{location}: unknown @weaver.rule.constraint.type {constraint_type}")
        if constraint_type in subject_required_constraint_types and not subjects:
            errors.append(f"{location}: constraint.type={constraint_type} requires @weaver.rule.subject")
        expected_category = CATEGORY_BY_CONSTRAINT_TYPE.get(str(constraint_type or ""))
        if expected_category and clause.get("category_zh") != expected_category:
            errors.append(
                f"{location}: constraint.type={constraint_type} requires @weaver.rule.category.zh: {expected_category}"
            )
        if constraint_type == "enum" and not clause.get("allowed_values"):
            errors.append(f"{location}: constraint.type=enum requires @weaver.rule.allowed_values")
        if constraint_type == "fixed_value" and not clause.get("expected_value"):
            errors.append(f"{location}: constraint.type=fixed_value requires @weaver.rule.expected_value")
        if constraint_type == "forbidden_presence":
            for subject in subjects:
                if subject.get("kind") not in {"field", "prefix"}:
                    errors.append(f"{location}: forbidden_presence subject must be field:* or prefix:*")
        if constraint_type in {"required_presence", "recommended_presence", "forbidden_presence"}:
            bucket = constraint_type.removesuffix("_presence")
            for subject in subjects:
                kind = subject.get("kind", "")
                value = subject.get("value", "")
                if not kind or not value:
                    continue
                presence_bucket_by_subject[(str(clause.get("entity", "")), kind, value)][bucket].append(location)
                if constraint_type in {"required_presence", "recommended_presence"}:
                    area = "resource_attributes" if str(clause.get("entity", "")).startswith("resource:") else "attributes"
                    positive_area_by_subject[(str(clause.get("signal", "")), kind, value)][area].append(location)
                if (
                    clause.get("signal") == "events"
                    and constraint_type == "required_presence"
                    and kind == "field"
                    and str(clause.get("entity", "")).startswith("event:")
                ):
                    event_required_subject_locations[str(clause.get("entity", ""))][value].append(location)
                if (
                    clause.get("signal") in {"traces", "spans"}
                    and constraint_type == "required_presence"
                    and kind == "field"
                    and str(clause.get("entity", "")).startswith("span:")
                ):
                    trace_required_subject_locations[str(clause.get("entity", ""))][value].append(location)
    for (entity, kind, value), buckets in sorted(presence_bucket_by_subject.items()):
        if len(buckets) <= 1:
            continue
        details = "; ".join(
            f"{bucket}: {', '.join(locations)}"
            for bucket, locations in sorted(buckets.items())
        )
        errors.append(
            f"{entity} {kind}:{value}: exact subject appears in multiple presence buckets ({details})"
        )
    for (signal, kind, value), areas in sorted(positive_area_by_subject.items()):
        if len(areas) <= 1:
            continue
        details = "; ".join(
            f"{area}: {', '.join(locations)}"
            for area, locations in sorted(areas.items())
        )
        errors.append(
            f"{signal} {kind}:{value}: subject has positive presence in both attributes and resource attributes ({details})"
        )
    common_event_required_subjects = set(event_required_subject_locations.get("event:common", {}))
    for entity, subjects in sorted(event_required_subject_locations.items()):
        if entity == "event:common":
            continue
        duplicates = sorted(set(subjects) & common_event_required_subjects)
        for value in duplicates:
            errors.append(
                f"{entity} field:{value}: event-specific required rule duplicates event:common required subject "
                f"({', '.join(subjects[value])})"
            )
    common_trace_required_subjects = set(trace_required_subject_locations.get("span:common", {}))
    for entity, subjects in sorted(trace_required_subject_locations.items()):
        if entity == "span:common":
            continue
        duplicates = sorted(set(subjects) & common_trace_required_subjects)
        for value in duplicates:
            errors.append(
                f"{entity} field:{value}: span-kind required rule duplicates span:common required subject "
                f"({', '.join(subjects[value])})"
            )
    return errors


def generate() -> int:
    expected_outputs = outputs()
    for path, content in expected_outputs.items():
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(content, encoding="utf-8")
        print(f"generated {rel(path)}")
    return 0


def check() -> int:
    drift: List[Tuple[Path, str]] = []
    expected_outputs = outputs()
    for path, expected in expected_outputs.items():
        if not path.exists():
            drift.append((path, "missing"))
            continue
        actual = path.read_text(encoding="utf-8")
        if actual != expected:
            drift.append((path, "out-of-date"))
    retired_specs = retired_spec_errors()
    generated_rego = generated_rego_errors()
    annotations = policy_annotation_errors()
    if drift:
        print("spec drift detected; run `make -C weaver spec-generate`:", file=sys.stderr)
        for path, reason in drift:
            print(f"  {reason}: {rel(path)}", file=sys.stderr)
    if retired_specs:
        print("retired YAML spec files detected:", file=sys.stderr)
        for error in retired_specs:
            print(f"  {error}", file=sys.stderr)
    if generated_rego:
        print("generated Rego drift detected:", file=sys.stderr)
        for error in generated_rego:
            print(f"  {error}", file=sys.stderr)
    if annotations:
        print("Rego rule annotation drift detected:", file=sys.stderr)
        for error in annotations:
            print(f"  {error}", file=sys.stderr)
    if drift or retired_specs or generated_rego or annotations:
        return 1
    print("spec-check ok")
    return 0


def main(argv: List[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description="Generate/check AiVision Rego metadata artifacts")
    parser.add_argument("command", choices=["generate", "check"])
    args = parser.parse_args(argv)
    if args.command == "generate":
        return generate()
    return check()


if __name__ == "__main__":
    raise SystemExit(main())
