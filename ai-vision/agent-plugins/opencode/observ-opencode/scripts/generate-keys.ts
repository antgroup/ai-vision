#!/usr/bin/env tsx
/**
 * Build-time key obfuscation and config embedding script.
 *
 * Reads EDITION env var (aivision | cowork), loads the corresponding
 * keys.json and configs/*.config.json, then generates:
 *   - src/keys.generated.ts   (XOR-encrypted Langfuse keys)
 *   - src/edition-config.generated.ts  (plaintext OTLP defaults)
 *
 * Usage:
 *   EDITION=aivision tsx scripts/generate-keys.ts
 *   tsx scripts/generate-keys.ts              # common edition (no keys/config)
 */

import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { randomBytes } from 'node:crypto';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = dirname(fileURLToPath(import.meta.url));
const ROOT = join(__dirname, '..');
const KEYS_OUT = join(ROOT, 'src', 'keys.generated.ts');
const CONFIG_OUT = join(ROOT, 'src', 'edition-config.generated.ts');

// Edition → config file name mapping
const CONFIG_NAMES: Record<string, string> = {
  aivision: 'aivision',
  cowork: 'cowork',
};

interface KeysJson {
  agent_product: string;
  prod_public_key: string;
  prod_secret_key: string;
  prod_host: string;
  gray_public_key: string;
  gray_secret_key: string;
  gray_host: string;
}

function xorEncrypt(plaintext: string): { enc: number[]; mask: number[] } {
  const buf = Buffer.from(plaintext, 'utf-8');
  const mask = randomBytes(buf.length);
  const enc = Buffer.alloc(buf.length);
  for (let i = 0; i < buf.length; i++) {
    enc[i] = buf[i]! ^ mask[i]!;
  }
  return {
    enc: Array.from(enc),
    mask: Array.from(mask),
  };
}

function formatArray(arr: number[]): string {
  if (arr.length === 0) return '[]';
  // Format in rows of 16 for readability
  const rows: string[] = [];
  for (let i = 0; i < arr.length; i += 16) {
    const chunk = arr.slice(i, i + 16);
    rows.push('  ' + chunk.map((b) => `0x${b.toString(16).padStart(2, '0')}`).join(', '));
  }
  return '[\n' + rows.join(',\n') + '\n]';
}

function generateEmpty(): string {
  return `// AUTO-GENERATED by scripts/generate-keys.ts — do not edit.
// Edition: common (no embedded keys)

export const EMBEDDED_EDITION = 'common';
export const HAS_EMBEDDED_KEYS = false;

export const PROD_PK_ENC: number[] = [];
export const PROD_PK_MASK: number[] = [];
export const PROD_SK_ENC: number[] = [];
export const PROD_SK_MASK: number[] = [];
export const PROD_HOST_ENC: number[] = [];
export const PROD_HOST_MASK: number[] = [];
export const GRAY_PK_ENC: number[] = [];
export const GRAY_PK_MASK: number[] = [];
export const GRAY_SK_ENC: number[] = [];
export const GRAY_SK_MASK: number[] = [];
export const GRAY_HOST_ENC: number[] = [];
export const GRAY_HOST_MASK: number[] = [];
`;
}

function generateEncrypted(edition: string, keys: KeysJson): string {
  const prodPk = xorEncrypt(keys.prod_public_key);
  const prodSk = xorEncrypt(keys.prod_secret_key);
  const prodHost = xorEncrypt(keys.prod_host || '');
  const grayPk = xorEncrypt(keys.gray_public_key);
  const graySk = xorEncrypt(keys.gray_secret_key);
  const grayHost = xorEncrypt(keys.gray_host || '');

  return `// AUTO-GENERATED by scripts/generate-keys.ts — do not edit.
// Edition: ${edition}

export const EMBEDDED_EDITION = '${edition}';
export const HAS_EMBEDDED_KEYS = true;

export const PROD_PK_ENC: number[] = ${formatArray(prodPk.enc)};
export const PROD_PK_MASK: number[] = ${formatArray(prodPk.mask)};
export const PROD_SK_ENC: number[] = ${formatArray(prodSk.enc)};
export const PROD_SK_MASK: number[] = ${formatArray(prodSk.mask)};
export const PROD_HOST_ENC: number[] = ${formatArray(prodHost.enc)};
export const PROD_HOST_MASK: number[] = ${formatArray(prodHost.mask)};
export const GRAY_PK_ENC: number[] = ${formatArray(grayPk.enc)};
export const GRAY_PK_MASK: number[] = ${formatArray(grayPk.mask)};
export const GRAY_SK_ENC: number[] = ${formatArray(graySk.enc)};
export const GRAY_SK_MASK: number[] = ${formatArray(graySk.mask)};
export const GRAY_HOST_ENC: number[] = ${formatArray(grayHost.enc)};
export const GRAY_HOST_MASK: number[] = ${formatArray(grayHost.mask)};
`;
}

// ── Config generation (plaintext, non-sensitive) ────────────────────────────

function generateEmptyConfig(): string {
  return `// AUTO-GENERATED by scripts/generate-keys.ts — do not edit.
// Edition: common (no embedded config)

export const HAS_EMBEDDED_CONFIG = false;
export const EMBEDDED_CONFIG: null = null;
export const EMBEDDED_METADATA: null = null;
`;
}

function generateEmbeddedConfig(
  edition: string,
  config: Record<string, unknown>,
  metadata: Record<string, unknown> | null,
): string {
  return `// AUTO-GENERATED by scripts/generate-keys.ts — do not edit.
// Edition: ${edition}

export const HAS_EMBEDDED_CONFIG = true;
export const EMBEDDED_CONFIG = ${JSON.stringify(config, null, 2)} as const;
export const EMBEDDED_METADATA = ${JSON.stringify(metadata, null, 2)} as const;
`;
}

// ── Main ────────────────────────────────────────────────────────────────────

const edition = process.env.EDITION?.trim() || '';

if (!edition || edition === 'common') {
  console.log('[generate] No EDITION set → common (no embedded keys/config)');
  writeFileSync(KEYS_OUT, generateEmpty(), 'utf-8');
  writeFileSync(CONFIG_OUT, generateEmptyConfig(), 'utf-8');
} else {
  // Keys
  const keyFile = join(ROOT, `${edition}.keys.json`);
  let raw: string;
  try {
    raw = readFileSync(keyFile, 'utf-8');
  } catch {
    console.error(`[generate] ERROR: Cannot read ${keyFile}`);
    console.error(`  Ensure ${edition}.keys.json exists in the project root.`);
    process.exit(1);
  }

  const keys: KeysJson = JSON.parse(raw);
  console.log(`[generate] Edition: ${edition}, product: ${keys.agent_product}`);
  writeFileSync(KEYS_OUT, generateEncrypted(edition, keys), 'utf-8');

  // Config
  const configName = CONFIG_NAMES[edition] || edition;
  const configFile = join(ROOT, 'configs', `${configName}.config.json`);
  if (existsSync(configFile)) {
    const config = JSON.parse(readFileSync(configFile, 'utf-8'));
    const metadataFile = join(ROOT, 'configs', `${configName}.metadata.json`);
    const metadata = existsSync(metadataFile)
      ? JSON.parse(readFileSync(metadataFile, 'utf-8'))
      : null;
    writeFileSync(CONFIG_OUT, generateEmbeddedConfig(edition, config, metadata), 'utf-8');
    console.log(`[generate] Config: ${configFile}`);
    if (metadata) console.log(`[generate] Metadata: ${metadataFile}`);
  } else {
    console.log(`[generate] No config file found at ${configFile}, skipping`);
    writeFileSync(CONFIG_OUT, generateEmptyConfig(), 'utf-8');
  }
}

console.log(`[generate] Written → ${KEYS_OUT}`);
console.log(`[generate] Written → ${CONFIG_OUT}`);
