import { writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { loadEditionConfig, resolveEdition } from './edition-config-source.mjs';

const packageRoot = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const destination = resolve(packageRoot, 'src', 'edition-config.generated.ts');
const edition = resolveEdition();
const { config, sourcePath } = loadEditionConfig(edition);

writeFileSync(destination, `// AUTO-GENERATED by scripts/generate-edition-config.mjs - do not edit.
// Edition: ${edition}

export const EMBEDDED_EDITION = ${JSON.stringify(edition)} as const;
export const EMBEDDED_CONFIG = ${JSON.stringify(config, null, 2)} as const;
`);

console.log(`[generate] Edition: ${edition}`);
console.log(`[generate] Config source: ${sourcePath}`);
console.log(`[generate] Written: ${destination}`);
