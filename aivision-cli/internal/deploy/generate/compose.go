// renderCompose emits a single compose.yaml covering every kind:container
// component. kind:process components are host-supervised (venv/node) with no
// image, so they are reported as skipped.
func renderCompose(app *runtime.App, comps []Resolved) ([]File, []string, error) {
	containers := containers(comps)
	if len(containers) == 0 {
		return nil, nil, fmt.Errorf("compose target: blueprint has no kind:container components")
	}
	containerSet := map[string]bool{}
	for _, c := range containers {
		containerSet[c.Name] = true
	}

	var warns []string
	for _, c := range app.BP.OrderedComponents() {
		if len(c.PreStart)+len(c.PostStart)+len(c.Discover) > 0 {
			warns = append(warns, "generic Compose export omits initialization and discovery hooks; it is not a complete product installation")
			break
		}
	}
	if skipped := skippedProcesses(comps); len(skipped) > 0 {
		warns = append(warns, fmt.Sprintf(
			"compose target skips host-process components (no image): %s — deploy them with the systemd target or run them under `aiv cast`",
			strings.Join(skipped, ", ")))
	}

	// Collect top-level networks and named volumes across all services.
	networks := map[string]bool{}
	volumes := map[string]bool{}

	var b strings.Builder
	b.WriteString("# Generated by aiv generate --target compose. DO NOT EDIT BY HAND.\n")
	b.WriteString("# Re-generate from the blueprint instead. Host-process components are not\n")
	b.WriteString("# representable here; see `aiv generate --target systemd`.\n")
	b.WriteString(fmt.Sprintf("name: %s\n\n", app.BP.Metadata.Namespace))

	// services
	b.WriteString("services:\n")
	for _, c := range containers {
		if c.Network != "" {
			networks[c.Network] = true
		}
		b.WriteString(fmt.Sprintf("  %s:\n", c.Name))
		if c.Title != "" {
			b.WriteString(fmt.Sprintf("    # %s\n", c.Title))
		}
		b.WriteString(fmt.Sprintf("    image: %s\n", yamlQuote(c.Image)))
		if c.ContainerName != "" {
			b.WriteString(fmt.Sprintf("    container_name: %s\n", yamlQuote(c.ContainerName)))
		}
		if len(c.Entrypoint) > 0 {
			b.WriteString("    entrypoint: " + yamlFlowSeq(c.Entrypoint) + "\n")
		}
		if len(c.Command) > 0 {
			b.WriteString("    command: " + yamlFlowSeq(c.Command) + "\n")
		}
		if c.Network != "" {
			b.WriteString("    networks: [" + yamlQuote(c.Network) + "]\n")
		}

		if c.MemoryLimit != "" {
			b.WriteString(fmt.Sprintf("    mem_limit: %s\n", yamlQuote(c.MemoryLimit)))
		}

		// ports (docker -p short syntax is valid compose syntax verbatim)
		if len(c.Ports) > 0 {
			b.WriteString("    ports:\n")
			for _, p := range c.Ports {
				b.WriteString(fmt.Sprintf("      - %s\n", yamlQuote(p)))
			}
		}

		// volumes: merge -v specs and --mount long specs into compose short syntax
		vols, named := composeVolumes(c)
		for _, v := range named {
			volumes[v] = true
		}
		if len(vols) > 0 {
			b.WriteString("    volumes:\n")
			for _, v := range vols {
				b.WriteString(fmt.Sprintf("      - %s\n", yamlQuote(v)))
			}
		}

		// environment (envFile values are already merged into Env by ResolveEnv)
		if len(c.Env) > 0 {
			b.WriteString("    environment:\n")
			for _, k := range sortedEnvKeys(c.Env) {
				b.WriteString(fmt.Sprintf("      %s: %s\n", k, yamlQuote(c.Env[k])))
			}
		}

		// depends_on: only container services can be referenced
		var deps []string
		for _, d := range c.DependsOn {
			if containerSet[d] {
				deps = append(deps, d)
			}
		}
		sort.Strings(deps)
		if len(deps) > 0 {
			b.WriteString("    depends_on: [" + strings.Join(deps, ", ") + "]\n")
		}

		// healthcheck
		if hc := composeHealthcheck(c); hc != "" {
			b.WriteString(hc)
		}
		b.WriteString("\n")
	}

	// top-level networks
	if len(networks) > 0 {
		b.WriteString("networks:\n")
		for _, n := range sortedKeys(networks) {
			b.WriteString(fmt.Sprintf("  %s:\n    name: %s\n", n, yamlQuote(n)))
		}
		b.WriteString("\n")
	}

	// top-level named volumes
	if len(volumes) > 0 {
		b.WriteString("volumes:\n")
		for _, v := range sortedKeys(volumes) {
			b.WriteString(fmt.Sprintf("  %s:\n    name: %s\n", v, yamlQuote(v)))
		}
		b.WriteString("\n")
	}

	return []File{{Path: "compose.yaml", Content: []byte(b.String())}}, warns, nil
}

// composeVolumes converts a component's -v and --mount specs into compose short
// syntax, returning the volume lines and any named volumes to declare top-level.
func composeVolumes(c Resolved) (lines []string, named []string) {
	for _, v := range c.Volumes {
		lines = append(lines, v)
		if n := volumeName(v); n != "" {
			named = append(named, n)
		}
	}
	for _, m := range c.Mounts {
		ms := parseMount(m)
		if ms.Source == "" || ms.Target == "" {
			continue
		}
		line := ms.Source + ":" + ms.Target
		if ms.ReadOnly {
			line += ":ro"
		}
		lines = append(lines, line)
		if ms.Type == "volume" {
			named = append(named, ms.Source)
		}
	}
	return lines, named
}

// composeHealthcheck renders a compose healthcheck block (indented, with a
// trailing newline) or "" when the component has no usable probe. TCP probes are
// translated to a container-side /dev/tcp check using the mapped container port.
func composeHealthcheck(c Resolved) string {
	if c.Health == nil {
		return ""
	}
	h := c.Health
	var test string
	var argv []string
	switch {
	case len(h.ExecArgv) > 0:
		argv = []string{"CMD"}
		for _, arg := range h.ExecArgv {
			// Compose interpolates dollar signs after blueprint expansion.
			argv = append(argv, strings.ReplaceAll(arg, "$", "$$"))
		}
	case h.Exec != "":
		test = h.Exec
		// The default datastore probe is a host-side docker exec command.
		// Compose already runs it in this service's container. Strip only
		// the exact own-container prefix, preserving the remaining shell text.
		if c.ContainerName != "" {
			for _, name := range []string{c.ContainerName, "'" + strings.ReplaceAll(c.ContainerName, "'", "'\\''") + "'"} {
				prefix := "docker exec " + name + " "
				if strings.HasPrefix(test, prefix) {
					test = strings.TrimPrefix(test, prefix)
					break
				}
			}
		}
	case h.HTTP != "":
		test = fmt.Sprintf("curl -fsS %s >/dev/null 2>&1 || exit 1", h.HTTP)
	case h.TCP != "":
		port := tcpContainerPort(c, h.TCP)
		if port == "" {
			return ""
		}
		test = fmt.Sprintf("bash -c 'exec 3<>/dev/tcp/127.0.0.1/%s' 2>/dev/null || exit 1", port)
	default:
		return ""
	}
	if len(argv) == 0 {
		argv = []string{"CMD-SHELL", test}
	}
	interval := h.Interval
	if interval == "" {
		interval = "5s"
	}
	timeout := h.Timeout
	if timeout == "" {
		timeout = "3s"
	}
	retries := h.Retries
	if retries <= 0 {
		retries = 3
	}
	var b strings.Builder
	b.WriteString("    healthcheck:\n")
	b.WriteString("      test: " + yamlFlowSeq(argv) + "\n")
	b.WriteString(fmt.Sprintf("      interval: %s\n", interval))
	b.WriteString(fmt.Sprintf("      timeout: %s\n", timeout))
	b.WriteString(fmt.Sprintf("      retries: %d\n", retries))
	return b.String()
}

// tcpContainerPort maps a host-side "ip:port" TCP probe to the container port by
// matching the published host port, falling back to the probe port itself.
func tcpContainerPort(c Resolved, tcp string) string {
	hostPort := tcp
	if i := strings.LastIndexByte(tcp, ':'); i >= 0 {
		hostPort = tcp[i+1:]
	}
	for _, p := range c.Ports {
		ps := parsePort(p)
		if ps.HostPort == hostPort && ps.ContainerPort != "" {
			return ps.ContainerPort
		}
	}
	return hostPort
}
